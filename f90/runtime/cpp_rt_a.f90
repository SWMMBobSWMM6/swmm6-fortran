  recursive function cpp_a_str_compare(x, y) result(r)
    class(cpp_str), intent(in) :: x, y
    integer(4) :: r
    integer(4) :: i, m, p, q
    m = min(x%n, y%n)
    do i = 0, m - 1
      p = iand(int(x%b%a(i), 4), 255)
      q = iand(int(y%b%a(i), 4), 255)
      if (p /= q) then
        r = merge(-1, 1, p < q)
        return
      end if
    end do
    r = x%n - y%n
