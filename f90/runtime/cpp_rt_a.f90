    integer(8), intent(in) :: v
    character(len=:), allocatable :: s
    if (v < 0) then
      s = '-' // cpp_a_udec8(not(v) + 1_8)
    else
      s = cpp_a_udec8(v)
    end if
  end function cpp_a_dec8

