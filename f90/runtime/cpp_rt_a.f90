  recursive function cpp_udiv8(a1, a2) result(zres)
    integer(8), value :: a1
    integer(8), value :: a2
    integer(8) :: zres
    integer(8) :: q, r
    if (a2 < 0) then
      ! a divisor >= 2**63: the quotient is 1 when a1 >= a2 (unsigned), else 0
      if (ieor(a1, CPP_A_SIGN8) >= ieor(a2, CPP_A_SIGN8)) then
        zres = 1
      else
        zres = 0
      end if
    else if (a1 >= 0) then
      zres = a1 / a2
    else
      q = ishft(ishft(a1, -1) / a2, 1)
      r = a1 - q * a2
      if (ieor(r, CPP_A_SIGN8) >= ieor(a2, CPP_A_SIGN8)) q = q + 1
      zres = q
    end if
  end function cpp_udiv8
