  recursive function cpp_u2d(a1) result(zres)
    integer(8), value :: a1
    real(8) :: zres
    ! C#'s ulong -> double: one rounding to nearest even (halve with the low bit kept sticky, convert, double)
    if (a1 >= 0) then
      zres = real(a1, 8)
    else
      zres = real(ior(ishft(a1, -1), iand(a1, 1_8)), 8) * 2.0_8
    end if
